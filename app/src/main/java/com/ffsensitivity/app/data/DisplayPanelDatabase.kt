/**
 * Curated panel-type database for popular models.
 * Used only when OEM props / EDID do not explicitly name the panel.
 * Unknown models stay Unknown — no brand-wide guessing.
 */
object DisplayPanelDatabase {

    fun lookup(brand: String = Build.BRAND, model: String = Build.MODEL, device: String = Build.DEVICE): String? {
        val candidates = linkedSetOf<String>()
        listOf(model, device, "$brand $model", model.replace("5G", "", ignoreCase = true)).forEach { raw ->
            val n = normalize(raw)
            if (n.isNotBlank()) candidates.add(n)
        }

        // 1) Exact normalized match
        for (c in candidates) {
            PANEL_BY_KEY[c]?.let { return it }
        }

        // 2) Fuzzy contains — always prefer the longest matching key
        var bestKey = ""
        var bestPanel: String? = null
        for (c in candidates) {
            if (c.length < 4) continue
            for ((key, panel) in PANEL_BY_KEY) {
                if (key.length < 6) continue
                val hit = c.contains(key) || (c.length >= 6 && key.contains(c))
                if (!hit) continue
                if (key.length > bestKey.length) {
                    bestKey = key
                    bestPanel = panel
                }
            }
        }
        return bestPanel
    }

    private fun normalize(raw: String): String {
        return raw.lowercase()
            .replace("realme", "realme")
            .replace("(", "")
            .replace(")", "")
            .replace("+", "plus")
            .replace(".", "")
            .replace(" ", "")
            .replace("-", "")
            .replace("_", "")
            .trim()
    }

